COUNTS = {"case_only": 15, "suffix": 40, "punctuation": 30, "typo": 45,
          "long_retail_name": 45}


def _match_case(template: str, ch: str) -> str:
    return ch.upper() if template.isupper() else ch


def make_typo(name: str, rng: random.Random) -> str:
    """Apply one random keyboard-style edit to a letter at a random position."""
    letters = [i for i, c in enumerate(name) if c.isalpha()]
    i = rng.choice(letters)
    op = rng.choice(["substitute", "delete", "double", "swap"])
    c = name[i]
    if op == "substitute":
        repl = rng.choice(QWERTY_NEIGHBOURS.get(c.lower(), "e"))
        return name[:i] + _match_case(c, repl) + name[i + 1:]
    if op == "delete":
        return name[:i] + name[i + 1:]
    if op == "double":
        return name[:i] + c + name[i:]
    # swap with the next character when it is a letter, else with the previous one
    j = i + 1 if i + 1 < len(name) and name[i + 1].isalpha() else i - 1
    if j < 0 or not name[j].isalpha():
        return name[:i] + name[i + 1:]
    a, b = min(i, j), max(i, j)
    return name[:a] + name[b] + name[a] + name[b + 1:]


def make_punctuation(name: str, rng: random.Random) -> str:
    ops = ["no_spaces", "hyphens", "underscores", "trailing_dot", "upper_bang",
           "strip_marks", "double_space", "dotted"]
    rng.shuffle(ops)
    for op in ops:
        if op == "no_spaces" and " " in name:
            out = name.replace(" ", "")
        elif op == "hyphens" and " " in name:
            out = name.replace(" ", "-")
        elif op == "underscores" and " " in name:
            out = name.replace(" ", "_")
        elif op == "trailing_dot":
            out = name + "."
        elif op == "upper_bang":
            out = name.upper() + "!"
        elif op == "strip_marks" and any(ch in name for ch in "'.-&"):
            out = "".join(" " if ch in ".-" else ch for ch in name if ch not in "'&").strip()
        elif op == "double_space" and " " in name:
            out = name.replace(" ", "  ", 1)
        elif op == "dotted" and len(normalize_alnum(name)) <= 4:
            out = ".".join(name.replace(" ", "")) + "."
        else:
            continue
        if out != name:
            return out
    return name + " ."


def make_case(name: str, rng: random.Random) -> str:
    ops = [str.lower, str.upper, str.title, lambda s: s[0].lower() + s[1:].upper()]
    rng.shuffle(ops)
    for op in ops:
        out = op(name)
        if out != name:
            return out
    return name.lower() + " "


def decorate_maybe(name: str, rng: random.Random, p: float) -> str:
    """With probability p, add a realistic suffix or gift card tail."""
    if rng.random() >= p:
        return name
    if rng.random() < 0.5:
        return name + rng.choice(SUFFIXES)
    return rng.choice(RETAIL_TEMPLATES).format(b=name)


def build() -> Tuple[List[str], List[Tuple[str, str, str]]]:
    rng = random.Random(SEED)
    master_norm = {normalize_alnum(m): m for m in MASTER}
    assert len(master_norm) == len(MASTER), "master list has normalised duplicates"
    rows: List[Tuple[str, str, str]] = []
    seen = set()

    def add(raw: str, true_master: str, case_type: str) -> bool:
        if raw in seen:
            return False
        n = normalize_alnum(raw)
        # A generated variant must not be another master brand in disguise.
        if n in master_norm and master_norm[n] != true_master:
            return False
        if not true_master and n in master_norm:
            return False
        seen.add(raw)
        rows.append((raw, true_master, case_type))
        return True

    def fill(case_type: str, make) -> None:
        pool = list(MASTER)
        rng.shuffle(pool)
        made = 0
        for m in pool:
            if made == COUNTS[case_type]:
                break
            if add(make(m), m, case_type):
                made += 1
        assert made == COUNTS[case_type], case_type

    fill("case_only", lambda m: make_case(m, rng))
    fill("suffix", lambda m: m + rng.choice(SUFFIXES))
    fill("punctuation", lambda m: make_punctuation(m, rng))

    def typo(m: str) -> str:
        out = make_typo(m, rng)
        if len(normalize_alnum(m)) >= 10 and rng.random() < 0.5:
            out = make_typo(out, rng)
        if normalize_alnum(out) == normalize_alnum(m):
            out = make_typo(m, rng)
        return out

    fill("typo", typo)
    fill("long_retail_name", lambda m: rng.choice(RETAIL_TEMPLATES).format(b=m))

    for raw, m in AND_AMPERSAND:
        assert add(raw, m, "and_ampersand"), raw
    for raw, m in ALIASES:
        assert add(raw, m, "alias"), raw
    for raw, m in LOOKALIKES:
        assert m in MASTER and normalize_alnum(raw) not in master_norm, raw
        assert add(decorate_maybe(raw, rng, 0.3), "", "lookalike_negative"), raw
    for raw in NOT_IN_MASTER:
        assert add(decorate_maybe(raw, rng, 0.5), "", "not_in_master"), raw

    return list(MASTER), rows


def to_csv(header: List[str], rows: List[Tuple]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    w.writerows(rows)
    return buf.getvalue()


def rendered() -> Dict[str, str]:
    master, rows = build()
    return {
        MASTER_PATH: to_csv(["brand"], [(m,) for m in master]),
        EVAL_PATH: to_csv(["raw_brand", "true_master", "case_type"], rows),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify the committed CSVs")
    args = ap.parse_args(argv)
    files = rendered()
    if args.check:
        bad = [p for p, text in files.items()
               if not os.path.exists(p) or open(p, encoding="utf-8").read() != text]
        if bad:
            print("Out of date:", *bad)
            return 1
        print("Synthetic CSVs match the generator.")
        return 0
    os.makedirs(DATA_DIR, exist_ok=True)
    for p, text in files.items():
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        print(f"Wrote {p} ({text.count(chr(10)) - 1} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
